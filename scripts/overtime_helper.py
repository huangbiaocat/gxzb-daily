# 标准工作时间定义（公共资源交易中心与政务机关通用）
WORK_START_TIME = "08:00:00"
WORK_END_TIME = "18:00:00"

WEEKDAY_NAMES = ["周一", "周二", "周三", "周四", "周五", "周六", "周日"]


def is_overtime_publication(pub_time: str) -> Tuple[bool, str]:
    """判断给定发布时间是否属于加班/非工作时间发布。

    返回: (is_overtime, reason)
    """
    if not pub_time or not isinstance(pub_time, str):
        return False, ""
    pub_time = pub_time.strip()
    if len(pub_time) < 10:
        return False, ""

    date_part = pub_time[:10]
    time_part = pub_time[11:19] if len(pub_time) >= 19 else pub_time[11:]
    hm = time_part[:5] if len(time_part) >= 5 else time_part

    # 1. 法定节假日
    if date_part in CN_HOLIDAYS:
        hname = CN_HOLIDAYS[date_part]
        tip = f"法定节假日加班发布（{hname} {hm}）" if hm else f"法定节假日加班发布（{hname}）"
        return True, tip

    # 解析星期
    try:
        dt = datetime.date.fromisoformat(date_part)
        weekday = dt.weekday()  # 0=周一, 5=周六, 6=周日
    except Exception:
        return False, ""

    # 2. 周末（排除调休上班日）
    if weekday in (5, 6) and date_part not in CN_COMPENSATORY_WORKDAYS:
        wname = WEEKDAY_NAMES[weekday]
        tip = f"周末加班发布（{wname} {hm}）" if hm else f"周末加班发布（{wname}）"
        return True, tip

    # 3. 工作日（含周一至周五，以及周末调休上班日）
    if time_part:
        if len(time_part) == 5:
            cmp_time = time_part + ":00"
        else:
            cmp_time = time_part

        if cmp_time >= WORK_END_TIME:
            return True, f"工作日下班后加班发布（{hm}）"
        if cmp_time < WORK_START_TIME:
            return True, f"工作日早间/凌晨加班发布（{hm}）"

    return False, ""


def annotate_item_overtime(item: Dict[str, Any]) -> Dict[str, Any]:
    """在字典条目中注入 is_overtime 和 overtime_reason 字段。"""
    pub_time = str(item.get("pub_time") or "")
    is_ot, reason = is_overtime_publication(pub_time)
    item["is_overtime"] = 1 if is_ot else 0
    item["overtime_reason"] = reason
    return item
